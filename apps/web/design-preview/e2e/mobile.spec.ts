import { test, expect } from '@playwright/test'

for (const locale of ['ar', 'en']) {
  test(`mobile page stands alone and menu owns navigation: ${locale}`, async ({ page, context }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await context.addCookies([{ name: 'nasq-design-locale', value: locale, url: 'http://127.0.0.1:4317' }])
    await page.goto('/list?module=projects')
    const menu = page.getByRole('button', { name: locale === 'ar' ? 'فتح القائمة' : 'Open menu', exact: true })
    await expect(menu).toBeVisible()
    await expect(page.locator('.preview-sidebar')).toBeHidden()
    await expect(page.locator('.preview-rail')).toBeHidden()
    await expect(page.locator('.preview-desktop-records')).toBeHidden()
    await expect(page.locator('.preview-mobile-records > li')).toHaveCount(6)
    const workspace = await page.locator('.preview-workspace').boundingBox()
    expect(workspace!.x).toBe(0)
    expect(workspace!.width).toBe(390)
    await menu.click()
    const panel = page.getByRole('dialog', { name: locale === 'ar' ? 'القائمة' : 'Navigation', exact: true })
    await expect(panel).toBeVisible()
    await expect(panel).toHaveAttribute('data-side', locale === 'ar' ? 'right' : 'left')
    await expect(panel.getByRole('link', { name: locale === 'ar' ? 'المشاريع' : 'Projects', exact: true })).toHaveAttribute('aria-current', 'page')
    await panel.getByRole('link', { name: locale === 'ar' ? 'الموارد البشرية' : 'Human resources', exact: true }).click()
    await expect(page).toHaveURL(/module=hr/)
    await expect(panel).toHaveCount(0)
    await expect(page.locator('.preview-mobile-records')).toContainText(locale === 'ar' ? 'سارة أحمد' : 'Sara Ahmed')
    await menu.click()
    await page.keyboard.press('Escape')
    await expect(panel).toHaveCount(0)
    await expect(menu).toBeFocused()
    await page.reload()
    await expect(page.locator('.preview-mobile-records')).toContainText(locale === 'ar' ? 'سارة أحمد' : 'Sara Ahmed')
    await menu.click()
    await page.setViewportSize({ width: 1440, height: 1000 })
    await expect(panel).toHaveCount(0)
    await expect(menu).toBeHidden()
    await expect(page.locator('.preview-rail')).toBeVisible()
    await expect(page.locator('.preview-sidebar')).toBeVisible()
    await expect(page.getByRole('table')).toBeVisible()
    await expect(page.locator('.preview-mobile-records')).toBeHidden()
  })
}

test('mobile navigation cannot discard a form draft without confirmation', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/form')
  await page.getByLabel('اسم السجل', { exact: true }).fill('مسودة الجوال')
  await page.getByRole('button', { name: 'فتح القائمة', exact: true }).click()
  const menu = page.getByRole('dialog', { name: 'القائمة', exact: true })
  await menu.getByRole('link', { name: 'الإعدادات', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'لديك تغييرات غير محفوظة' })).toBeVisible()
  await page.getByRole('button', { name: 'البقاء في الصفحة', exact: true }).click()
  await expect(menu).toBeVisible()
  await expect(page).toHaveURL(/\/form$/)
  await menu.getByRole('button', { name: 'إغلاق', exact: true }).click()
  await expect(page.getByLabel('اسم السجل', { exact: true })).toHaveValue('مسودة الجوال')
  await page.getByRole('button', { name: 'فتح القائمة', exact: true }).click()
  await menu.getByRole('link', { name: 'الإعدادات', exact: true }).click()
  await page.getByRole('button', { name: 'تجاهل التغييرات والمغادرة', exact: true }).click()
  await expect(page).toHaveURL(/\/settings/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
})

test('mobile filters and full-width record sheets preserve list context', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/list?module=projects')
  await page.getByRole('button', { name: 'البحث والفلاتر', exact: true }).click()
  await page.getByLabel('البحث بالاسم', { exact: true }).fill('توحيد')
  await page.keyboard.press('Escape')
  await expect(page.locator('.preview-mobile-records > li')).toHaveCount(1)
  await page.getByRole('button', { name: 'توحيد الخدمات الرقمية', exact: true }).click()
  const sheet = page.locator('.preview-sheet')
  await expect(sheet).toBeVisible()
  await expect.poll(async () => (await sheet.boundingBox())!.x).toBe(0)
  expect((await sheet.boundingBox())!.width).toBe(390)
  await page.reload()
  await expect(sheet).toBeVisible()
  await sheet.getByRole('button', { name: 'إغلاق', exact: true }).click()
  await expect(sheet).toHaveCount(0)
  expect(new URL(page.url()).searchParams.get('q')).toBe('توحيد')
  await expect(page.locator('.preview-mobile-records > li')).toHaveCount(1)
})

test('large text and all mobile recipes fit a narrow viewport', async ({ page, context }) => {
  await page.setViewportSize({ width: 320, height: 900 })
  await context.addCookies([{ name: 'nasq-design-appearance', value: encodeURIComponent(JSON.stringify({ mode: 'dark', fontSize: 'large' })), url: 'http://127.0.0.1:4317' }])
  await page.emulateMedia({ reducedMotion: 'reduce' })
  for (const view of ['dashboard', 'list', 'detail', 'form', 'settings', 'components']) {
    await page.goto(`/${view}`)
    await expect(page.locator('fieldset')).toBeEnabled()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), view).toBe(true)
    await expect(page.locator('.preview-sidebar')).toBeHidden()
  }
  await page.getByRole('button', { name: 'فتح القائمة', exact: true }).click()
  const menu = page.locator('.preview-mobile-menu')
  const box = await menu.boundingBox()
  expect(box!.x).toBeGreaterThanOrEqual(0)
  expect(box!.x + box!.width).toBeLessThanOrEqual(320)
  await expect(menu.getByRole('link', { name: 'المكونات والحالات', exact: true })).toBeVisible()
})
