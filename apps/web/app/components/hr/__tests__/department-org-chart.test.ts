import { readFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { describe, expect, it } from 'vitest'

const hrRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const chartSource = readFileSync(resolve(hrRoot, 'DepartmentOrgChart.vue'), 'utf8')
const pageSource = readFileSync(resolve(hrRoot, '../../pages/hr/departments/index.vue'), 'utf8')
const ar = readFileSync(resolve(hrRoot, '../../../i18n/locales/ar/hr.json'), 'utf8')
const en = readFileSync(resolve(hrRoot, '../../../i18n/locales/en/hr.json'), 'utf8')

describe('department org chart surface', () => {
  it('wires a third canvas view onto existing routes without new privileges', () => {
    expect(pageSource).toContain("route.query.view === 'canvas'")
    expect(pageSource).toContain("view: 'canvas'")
    expect(pageSource).toContain('hr-departments-view-canvas')
    expect(pageSource).toContain('hr.depts.orgChart')
    expect(pageSource).toContain('DepartmentOrgChart')
    expect(pageSource).toContain(':return-to="route.fullPath"')
    expect(pageSource).toContain("view: tree ? 'tree' : undefined")
    expect(pageSource).toContain('DepartmentTree')
    expect(pageSource).toContain('DepartmentTable')

    expect(chartSource).toContain('filterDepartmentTree')
    expect(chartSource).toContain('layoutDepartmentOrgChart')
    expect(chartSource).toContain('returnToQuery')
    expect(chartSource).toContain('/hr/departments/')
    expect(chartSource).toContain('hr-department-org-chart')
    expect(chartSource).toContain('hr-org-zoom-in')
    expect(chartSource).toContain('hr-org-zoom-out')
    expect(chartSource).toContain('hr-org-zoom-fit')
     expect(chartSource).not.toContain('requestFullscreen')
     expect(chartSource).not.toContain('exitFullscreen')
     expect(chartSource).not.toContain('fullscreenchange')
     expect(chartSource).toContain('hr-org-chart-expanded')
     expect(chartSource).toContain('aria-pressed')
     expect(chartSource).toContain("event.key === 'Escape'")
     expect(chartSource).toContain("document.body.style.overflow")
    expect(chartSource).toContain('background: var(--background)')
    expect(chartSource).not.toContain('hsl(var(--background))')
    expect(chartSource).not.toMatch(/background:\s*hsl\(/)
    expect(chartSource).toContain('if (next) previousBodyOverflow = document.body.style.overflow')
    expect(chartSource).toContain('if (fullscreen.value) document.body.style.overflow = previousBodyOverflow')
    expect(chartSource).toContain('line-clamp-2')
    expect(chartSource).toContain('dir="ltr"')
    expect(chartSource).toContain('data-org-node-text')
    expect(chartSource).toContain('insetInlineStart')
    expect(chartSource).toContain('data-from')
    expect(chartSource).toContain("pointerType === 'touch'")
    expect(chartSource).toContain('h-[calc(100svh-14rem)]')
    expect(chartSource).toContain('overflow-auto')
    expect(chartSource).not.toContain('origin-top-left')
    expect(chartSource).not.toContain('Dialog')
    expect(chartSource).not.toContain('Sheet')
    expect(chartSource).not.toContain('can(')

    expect(ar).toContain('"orgChart": "الرسم التنظيمي"')
    expect(en).toContain('"orgChart": "Org chart"')
     expect(en).toContain('"fullscreen": "Full page"')
     expect(en).toContain('"fullscreenExit": "Back to normal view"')
     expect(ar).toContain('"fullscreen": "عرض الصفحة بالكامل"')
     expect(ar).toContain('"fullscreenExit": "العودة للعرض العادي"')
  })
})
