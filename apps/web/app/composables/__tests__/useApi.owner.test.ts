import { afterEach, expect, it, vi } from 'vitest'
import { createSSRApp } from 'vue'
import { QueryClient } from '@tanstack/vue-query'
import { clearTenantSuspension, isTenantSuspended, onTenantSuspension } from '../../utils/tenantSuspension'
import { useApi } from '../useApi'
import { createSessionQueryScope, sessionQueryOwnerKey, sessionQueryScopeKey } from '../../lib/sessionQueryScope'

const clients: QueryClient[] = []
afterEach(() => { clients.splice(0).forEach(client => client.clear()); vi.unstubAllGlobals(); clearTenantSuspension() })
function fixture(publicView = false, component = true) {
  const scope = createSessionQueryScope(() => { const client = new QueryClient(); clients.push(client); return client }, '7:1', publicView)
  const app = createSSRApp({ render: () => null })
  app.provide(sessionQueryScopeKey, scope)
  if (component) app.provide(sessionQueryOwnerKey, scope.current.value)
  scope.bind()
  vi.stubGlobal('useI18n', () => ({ t: (key: string) => key, te: () => false, locale: { value: 'en' } }))
  const api = app.runWithContext(useApi)
  return { scope, ...api }
}
function deferred<T>() { let resolve!: (value: T) => void; let reject!: (reason: unknown) => void; const promise = new Promise<T>((done, fail) => { resolve = done; reject = fail }); return { promise, resolve, reject } }

it('does not start a chained private request from a retired owner', async () => {
  const view = fixture()
  const fetch = vi.fn(async () => ({ ok: true }))
  vi.stubGlobal('$fetch', fetch)
  await view.$api('/api/v1/projects')
  view.scope.prepare('7:2', false)
  await expect(view.$api('/api/v1/projects/1/approve', { method: 'POST', body: {} })).rejects.toMatchObject({ name: 'AbortError' })
  expect(fetch).toHaveBeenCalledTimes(1)
})
it('settles an accepted write as a nonretryable cancellation for its retired caller', async () => {
  const view = fixture()
  const held = deferred<{ ok: boolean }>()
  const fetch = vi.fn(() => held.promise)
  vi.stubGlobal('$fetch', fetch)
  const operation = view.$api('/api/v1/projects/1', { method: 'PATCH', body: {} })
  view.scope.prepare('7:2', false)
  held.resolve({ ok: true })
  await expect(operation).rejects.toMatchObject({ name: 'AbortError' })
  expect(fetch).toHaveBeenCalledTimes(1)
})
it('does not publish a retired tenant suspension error into the current session', async () => {
  const view = fixture()
  vi.stubGlobal('window', {})
  const suspended = vi.fn()
  onTenantSuspension(suspended)
  const held = deferred<never>()
  vi.stubGlobal('$fetch', () => held.promise)
  const operation = view.$api('/api/v1/projects')
  view.scope.prepare('7:2', false)
  held.reject({ statusCode: 403, data: { code: 'tenant_suspended', message: 'old suspended tenant' } })
  await expect(operation).rejects.toMatchObject({ name: 'AbortError' })
  expect(suspended).not.toHaveBeenCalled()
  expect(isTenantSuspended()).toBe(false)
})
