it('captures each root request independently and ignores a pending old root session error', async () => {
  const view = fixture(false, false)
  vi.stubGlobal('window', {})
  const suspended = vi.fn()
  onTenantSuspension(suspended)
  const held = deferred<never>()
  const fetch = vi.fn().mockImplementationOnce(() => held.promise).mockResolvedValue({ company: 2 })
  vi.stubGlobal('$fetch', fetch)
  const old = view.$api('/api/v1/me/appearance', { method: 'PATCH', body: {} })
  view.scope.prepare('7:2', false)
  await expect(view.$api('/api/v1/me/appearance', { method: 'PATCH', body: {} })).resolves.toEqual({ company: 2 })
  held.reject({ statusCode: 403, data: { code: 'tenant_suspended', message: 'old' } })
  await expect(old).rejects.toMatchObject({ name: 'AbortError' })
  expect(fetch).toHaveBeenCalledTimes(2)
  expect(suspended).not.toHaveBeenCalled()
})
it('guards download dispatch and completion with the captured component owner', async () => {
  const view = fixture()
  const held = deferred<{ _data: Blob; headers: Headers }>()
  const raw = vi.fn(() => held.promise)
  vi.stubGlobal('$fetch', Object.assign(vi.fn(), { raw }))
  const old = view.$download('/api/v1/hr/payroll/bank-file', { method: 'POST' })
  view.scope.prepare('7:2', false)
  held.resolve({ _data: new Blob(['old data']), headers: new Headers() })
  await expect(old).rejects.toMatchObject({ name: 'AbortError' })
  await expect(view.$download('/api/v1/hr/payroll/bank-file', { method: 'POST' })).rejects.toMatchObject({ name: 'AbortError' })
  expect(raw).toHaveBeenCalledTimes(1)
})

it('fences a root private API result by actor even while the public realm client stays active', async () => {
  const view = fixture(true, false)
  const before = view.scope.current.value.client
  const held = deferred<{ id: number }>()
  const fetch = vi.fn().mockImplementationOnce(() => held.promise).mockResolvedValue({ id: 2 })
  vi.stubGlobal('$fetch', fetch)
  const old = view.$api('/api/v1/me/appearance', { method: 'PATCH', body: {} })
  view.scope.prepare('7:2', true)
  expect(view.scope.current.value.client).toBe(before)
  held.resolve({ id: 1 })
  await expect(old).rejects.toMatchObject({ name: 'AbortError' })
  await expect(view.$api('/api/v1/me/appearance', { method: 'PATCH', body: {} })).resolves.toEqual({ id: 2 })
  expect(fetch).toHaveBeenCalledTimes(2)
})
