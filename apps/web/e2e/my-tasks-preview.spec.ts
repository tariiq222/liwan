import { expect, test } from '@playwright/test'
import { enterFoundation } from './support/uxFoundations'

test.skip(process.env.E2E_MY_TASKS_STATEFUL !== '1', 'Requires the isolated in-memory MY_TASKS_STATEFUL=1 preview; no Odoo writes are permitted.')
test('a real preview session completes create edit collaboration state change and project handoff', async ({ page }) => {
  test.setTimeout(90_000)
  await enterFoundation(page, '/my-tasks')
  await page.getByRole('link', { name: 'مهمة شخصية جديدة', exact: true }).first().click()
  const title = `رحلة معاينة مهامي ${Date.now()}`
  await page.getByLabel('عنوان المهمة', { exact: true }).fill(title)
  await page.getByTestId('my-task-form-submit').click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'تعديل', exact: true }).click()
  await expect(page).toHaveURL(/\/my-tasks\/\d+\/edit/)
  await page.getByRole('textbox', { name: 'الوصف', exact: true }).fill('وصف محفوظ في جلسة المعاينة')
  await page.getByRole('button', { name: 'حفظ التغييرات', exact: true }).click()
  await expect(page.getByText('وصف محفوظ في جلسة المعاينة', { exact: true })).toBeVisible()
  await page.getByPlaceholder('اكتب تعليقًا').fill('تعليق معاينة محفوظ')
  await page.getByRole('button', { name: 'نشر التعليق', exact: true }).click()
  await expect(page.getByTestId('my-task-comments').getByText('تعليق معاينة محفوظ', { exact: true })).toBeVisible()
  await page.getByPlaceholder('عنوان المهمة الفرعية').fill('خطوة تنفيذ المعاينة')
  await page.getByRole('button', { name: 'إضافة مهمة فرعية', exact: true }).click()
  await page.getByRole('button', { name: 'إنجاز: خطوة تنفيذ المعاينة', exact: true }).click()
  await expect(page.getByTestId('my-task-subtasks-progress')).toHaveText('1 من 1 منجزة')
  await page.locator('input[type="file"]').setInputFiles({ name: 'preview-journey.txt', mimeType: 'text/plain', buffer: Buffer.from('synthetic preview only') })
  const attachment = page.getByRole('link', { name: 'preview-journey.txt', exact: true })
  await expect(attachment).toBeVisible()
  const download = await page.request.get((await attachment.getAttribute('href'))!)
  expect(await download.text()).toBe('synthetic preview only')
  await page.getByRole('button', { name: 'إنجاز', exact: true }).click()
  await expect(page.getByTestId('my-task-state')).toHaveText('منجزة')
  await page.getByRole('button', { name: 'إعادة فتح', exact: true }).click()
  await expect(page.getByTestId('my-task-state')).toHaveText('مفتوحة')
  await page.getByRole('button', { name: 'المزيد', exact: true }).click()
  await page.getByRole('menuitem', { name: 'تحويل إلى مهمة مشروع', exact: true }).click()
  const convert = page.getByTestId('my-task-convert')
  await convert.getByRole('button', { name: 'المشروع', exact: true }).click()
  await page.getByRole('option', { name: 'مشروع ألفا', exact: true }).click()
  await convert.getByRole('button', { name: 'تحويل المهمة', exact: true }).click()
  await convert.getByRole('button', { name: 'نعم، حوّل المهمة', exact: true }).click()
  await expect(page).toHaveURL(/\/projects\/1\/tasks\/\d+$/)
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
})
