import { test, expect } from '@playwright/test'

// These are the two actual views reported by Tariq, not an invalid "overview" tab.
test('project summary and task detail use the reference cards without legacy nested panels', async ({ page, baseURL }, testInfo) => {
  test.setTimeout(90_000)
  if (!baseURL?.includes(':3469')) throw new Error('Isolated migration runtime required')
  expect((await page.request.post('/api/auth/login', { data: { login: 'admin', password: 'admin' } })).ok()).toBeTruthy()
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const created = await page.request.post('/api/v1/projects', { data: { name: `مطابقة المرجع ${Date.now()}`, date_start: '2026-01-01', date_end: '2030-12-31' } })
  expect(created.status()).toBe(201)
  const project = await created.json()
  expect((await page.request.patch(`/api/v1/projects/${project.id}`, { data: { nasq_completion_approval: 'none' } })).ok()).toBeTruthy()
  const createdTask = await page.request.post('/api/v1/tasks', { data: { name: 'مراجعة واجهات المشروع', project_id: project.id } })
  expect(createdTask.status()).toBe(201)
  const task = await createdTask.json()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`/projects/${project.id}?tab=summary`)
  const summary = page.getByTestId('project-overview')
  await expect(summary).toBeVisible()
  await expect(summary.locator('.nasq-panel-header,.nasq-project-toolbar,.nasq-metrics')).toHaveCount(0)
  await expect(summary.getByText('نسبة الإنجاز', { exact: true })).toBeVisible()
  await expect(summary.locator('[data-slot="indicator"]')).toHaveCSS('width', '0px')
  const progressLabel = summary.getByText('نسبة الإنجاز', { exact: true })
  const fontRatio = await progressLabel.evaluate(el => parseFloat(getComputedStyle(el).fontSize) / parseFloat(getComputedStyle(document.documentElement).fontSize))
  expect(fontRatio).toBeCloseTo(0.928571, 3)
  await expect(summary.locator('section > [data-slot="root"]').first()).toHaveCSS('background-color', 'rgb(255, 255, 255)')
  await expect(page.getByTestId('project-tab-meetings')).toHaveAttribute('href', `/projects/${project.id}/meetings`)
  await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => undefined))) })
  await page.screenshot({ path: testInfo.outputPath('reference-project-summary.png'), fullPage: true })
  await page.goto(`/projects/${project.id}/tasks/${task.id}`)
  const sheet = page.locator('.nasq-ui-route-sheet')
  await expect(sheet.getByRole('heading', { name: task.name, exact: true })).toBeVisible()
  await expect(sheet.locator('.nasq-panel-header,.task-detail-card.nasq-panel')).toHaveCount(0)
  await expect(sheet.getByRole('tab', { name: 'التفاصيل', exact: true })).toBeVisible()
  await sheet.getByRole('tab', { name: 'الوصف', exact: true }).click()
  await expect(sheet.getByRole('button', { name: 'إضافة وصف', exact: true })).toBeEnabled()
  await page.evaluate(async () => { await Promise.all(document.getAnimations().filter(a => a.effect?.getTiming().iterations !== Infinity).map(a => a.finished.catch(() => undefined))) })
  await page.screenshot({ path: testInfo.outputPath('reference-task-detail.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(async () => (await sheet.boundingBox())?.width).toBeGreaterThan(389)
  await page.screenshot({ path: testInfo.outputPath('reference-task-detail-mobile.png'), fullPage: true })
  await sheet.getByTestId('task-description-edit').click()
  const editor = sheet.getByTestId('task-description-editor')
  await editor.locator('[contenteditable="true"]').fill('وصف محفوظ من الواجهة المطابقة للمرجع')
  await editor.locator('button[type="submit"]').click()
  await expect.poll(async () => (await (await page.request.get(`/api/v1/tasks/${task.id}`)).json()).description_html).toContain('وصف محفوظ من الواجهة المطابقة للمرجع')
  expect((await page.request.post('/api/v1/tasks', { data: { name: 'مهمة باقية', project_id: project.id } })).status()).toBe(201)
  expect((await page.request.post(`/api/v1/tasks/${task.id}/transition`, { data: { state: 'done' } })).ok()).toBeTruthy()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(`/projects/${project.id}?tab=summary`)
  await expect(summary.getByText('50%', { exact: true })).toBeVisible()
  await expect.poll(async () => summary.locator('[data-slot="indicator"]').evaluate(el => el.getBoundingClientRect().width / el.parentElement!.getBoundingClientRect().width)).toBeCloseTo(0.5, 2)
  expect(errors).toEqual([])
})
