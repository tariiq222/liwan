import { test, expect, type Page } from '@playwright/test'

test.skip(process.env.E2E_PROJECT_POPUPS !== '1', 'Isolated project mock only')
test.beforeEach(async ({ page }) => {
  await page.goto('/login')
  await page.getByLabel('اسم المستخدم').fill('admin')
  await page.getByLabel('كلمة المرور', { exact: true }).fill('admin')
  await page.getByRole('button', { name: 'دخول', exact: true }).click()
  await expect(page).not.toHaveURL(/\/login/)
})
async function openAlpha(page: Page) {
  // The row link only knows the remembered section after hydration (localStorage is client-only).
  await expect(page.getByTestId('context-sidebar-toggle')).toBeEnabled()
  await page.getByTestId('project-card').filter({ hasText: 'مشروع ألفا' }).getByRole('link', { name: 'مشروع ألفا', exact: true }).click()
}
test('project reentry restores section filters and keeps the new list origin', async ({ page }) => {
  await page.goto('/projects/1/register?q=اعتماد&kind=risk')
  await expect(page.getByRole('link', { name: 'إضافة خطر أو مشكلة' })).toBeVisible()
  await expect(page.getByTestId('project-workspace-settings')).toBeVisible()
  await page.goto('/projects?mine=1')
  await openAlpha(page)
  await expect(page).toHaveURL(/\/projects\/1\/register\?/)
  await expect(page.getByRole('textbox', { name: 'بحث عن خطر أو مشكلة' })).toHaveValue('اعتماد')
  expect(new URL(page.url()).searchParams.get('projectListReturnTo')).toBe('/projects?mine=1')
  await page.goto('/projects/1?tab=summary')
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('مشروع ألفا')
  await expect(page.getByTestId('project-tab-summary')).toHaveAttribute('aria-current', 'page')
})
test('task board survives leaving the project and a browser refresh', async ({ page }) => {
  await page.goto('/projects/1?tab=tasks&view=board&q=تصميم')
  await expect(page.getByTestId('project-workspace-settings')).toBeVisible()
  await page.goto('/projects')
  await page.reload()
  await openAlpha(page)
  await expect(page).toHaveURL(/view=board/)
  expect(new URL(page.url()).searchParams.get('q')).toBe('تصميم')
})
test('opening a create form does not replace the last workspace section', async ({ page }) => {
  await page.goto('/projects/1/register?q=اعتماد')
  await expect(page.getByRole('link', { name: 'إضافة خطر أو مشكلة' })).toBeVisible()
  await page.getByRole('link', { name: 'إضافة خطر أو مشكلة' }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.goto('/projects')
  await openAlpha(page)
  await expect(page).toHaveURL(/\/projects\/1\/register\?/)
  await expect(page.getByRole('dialog')).toHaveCount(0)
})
test('project sections are in-page tabs while the sidebar keeps the projects module', async ({ page }) => {
  await page.goto('/projects/1')
  await expect(page.getByTestId('project-workspace-settings')).toBeVisible()
  const sidebar = page.getByTestId('application-navigation')
  await expect(sidebar.getByTestId('projects-context-sub-list')).toBeVisible()
  await expect(sidebar.getByTestId('context-link-project-dashboard')).toBeVisible()
  await expect(sidebar.getByTestId('projects-quick-view-mine')).toBeVisible()
  await expect(sidebar.getByRole('heading', { name: 'العمل اليومي' })).toHaveCount(0)
  await expect(sidebar.getByRole('heading', { name: 'متابعة المشروع' })).toHaveCount(0)
  const tabs = await page.getByTestId('project-workspace-tabs').getByRole('link').allTextContents()
  expect(tabs.map(s => s.trim())).toEqual(['الملخص', 'المهام', 'التخطيط', 'الحوكمة', 'المالية', 'الاجتماعات', 'التحديثات'])
  await expect(page.getByTestId('project-planning-tabs')).toHaveCount(0)
  await expect(page.getByTestId('project-governance-tabs')).toHaveCount(0)
  await page.getByTestId('project-tab-planning').click()
  await expect(page.getByTestId('project-planning-tabs')).toBeVisible()
  const planning = await page.getByTestId('project-planning-tabs').getByRole('link').allTextContents()
  expect(planning.map(s => s.trim())).toEqual(['الجدول الزمني', 'المعالم'])
  await page.getByTestId('project-tab-governance').click()
  await expect(page.getByTestId('project-governance-tabs')).toBeVisible()
  await expect(page.getByTestId('governance-tab-charter')).toHaveAttribute('aria-current', 'page')
  const governance = await page.getByTestId('project-governance-tabs').getByRole('link').allTextContents()
  expect(governance.map(s => s.trim())).toEqual(['ملف المشروع', 'أصحاب المصلحة', 'المسؤوليات RACI', 'المخاطر والمشكلات'])
  await expect(page.locator('main h1')).toHaveCount(1)
})
test('project task uses tabs instead of stacked cards', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto('/projects/1/tasks/101')
  const tabs = page.getByTestId('task-detail-tabs')
  await expect(tabs.getByRole('tab', { name: 'التفاصيل', exact: true })).toHaveAttribute('data-state', 'active')
  await expect(page.getByTestId('task-activity-card')).toBeHidden()
  await tabs.getByRole('tab', { name: 'المهام الفرعية', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'المهام الفرعية', exact: true })).toBeVisible()
  await tabs.getByRole('tab', { name: 'التفاصيل', exact: true }).click()
  await expect(page.getByTestId('task-description')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('project-task.png'), fullPage: true })
  await page.goto('/tasks/101')
  await expect(page.getByTestId('task-detail-tabs')).toBeVisible()
  await expect(page.locator('.task-optional-details')).toHaveCount(0)
})
