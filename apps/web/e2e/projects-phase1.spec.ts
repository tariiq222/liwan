test('governance pagination and matrix searches reach tasks and stakeholders beyond initial pages', async ({ page }) => {
  test.setTimeout(120_000)
  const p = await project(page, 'تصفح سجل كبير')
  const taskItems = []
  for (let i = 0; i < 51; i++) taskItems.push(await task(page, p.id, `مهمة ${String(i).padStart(3, '0')}`))
  let lastStakeholder: { id: number; name: string } | undefined
  for (let i = 0; i < 201; i++) {
    lastStakeholder = await json(await page.request.post(`/api/v1/projects/${p.id}/stakeholders`, { data: { name: `جهة ${String(i).padStart(3, '0')}` } }), 201)
  }
  await page.goto(`/projects/${p.id}/stakeholders`)
  const results = page.getByRole('navigation', { name: 'صفحات النتائج', exact: true })
  await expect(results).toContainText('201')
  for (let i = 0; i < 4; i++) {
    await results.getByRole('button', { name: 'التالي', exact: true }).click()
    await expect(page).toHaveURL(url => url.searchParams.get('offset') === String((i + 1) * 50))
  }
  await expect(page.getByRole('link', { name: lastStakeholder!.name, exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('link', { name: lastStakeholder!.name, exact: true })).toBeVisible()
  await page.goto(`/projects/${p.id}/raci`)
  const taskPages = page.getByRole('navigation', { name: 'المهمة', exact: true })
  await expect(taskPages).toContainText('51')
  const firstNames = await page.locator('tbody th').allTextContents()
  const missing = taskItems.find(item => !firstNames.some(name => name.includes(item.name)))!
  await taskPages.getByRole('button', { name: 'التالي', exact: true }).click()
  await expect(page.locator('tbody th')).toHaveCount(1)
  await expect(page.locator('tbody th')).toContainText(missing.name)
  await page.locator('#raci-stakeholder-search').fill(lastStakeholder!.name)
  const cell = page.getByRole('combobox', { name: `${missing.name} — ${lastStakeholder!.name} — الدور`, exact: true })
  await expect(cell).toBeEnabled()
  await cell.selectOption('C')
  await expect(cell).toHaveValue('C')
  await page.locator('#raci-task-search').fill(missing.name)
  await expect(cell).toHaveValue('C')
  const rows = await json(await page.request.get(`/api/v1/projects/${p.id}/raci?task_ids=${missing.id}&stakeholder_ids=${lastStakeholder!.id}`))
  expect(rows.items).toContainEqual(expect.objectContaining({ role: 'C' }))
  const viewport = new URL(page.url()).pathname + new URL(page.url()).search
  await page.reload()
  await expect(cell).toHaveValue('C')
  await expect(page.locator('#raci-task-search')).toHaveValue(missing.name)
  await expect(page.locator('#raci-stakeholder-search')).toHaveValue(lastStakeholder!.name)
  await page.getByRole('link', { name: lastStakeholder!.name, exact: true }).click()
  await page.locator('a').filter({ hasText: 'رجوع' }).click()
  await expect(page).toHaveURL(url => url.pathname + url.search === viewport)
  await expect(cell).toHaveValue('C')
})
