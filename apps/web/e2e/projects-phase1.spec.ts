test('schedule edits persist, preserve the return URL and show legacy deadline-only tasks', async ({ page }) => {
  const p = await project(page, 'جدولة المرحلة الأولى')
  const t = await task(page, p.id, 'تنفيذ المهمة المجدولة')
  const legacy = await task(page, p.id, 'موعد نهاية سابق')
  const markers = []
  for (const name of ['معلم', 'اسم معلم طويل لا يغير موضع موعده في الجدول الزمني']) {
    markers.push(await json(await page.request.post(`/api/v1/projects/${p.id}/milestones`, { data: { name, deadline: '2030-04-05' } }), 201))
  }
  await json(await page.request.patch(`/api/v1/tasks/${legacy.id}`, { data: { date_deadline: '2030-04-15T00:00:00Z' } }))
  const returnTo = `/projects/${p.id}/schedule?scale=month`
  await page.goto(`/projects/${p.id}/schedule/tasks/${t.id}?returnTo=${encodeURIComponent(returnTo)}`)
  await expect(page.locator('#planned-start')).toBeEnabled()
  await page.locator('#planned-start').fill('2030-04-01')
  await page.locator('#planned-end').fill('2030-04-05')
  await page.getByRole('button', { name: 'حفظ', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/projects/${p.id}/schedule\\?scale=month$`))
  await expect(page.getByText(t.name, { exact: true }).first()).toBeVisible()
  await expect(page.getByText(legacy.name, { exact: true }).first()).toBeVisible()
  const schedule = await json(await page.request.get(`/api/v1/projects/${p.id}/schedule`))
  expect(schedule.tasks.find((item: { id: number }) => item.id === t.id)).toMatchObject({ start: '2030-04-01', end: '2030-04-05' })
  expect(schedule.tasks.find((item: { id: number }) => item.id === legacy.id)).toMatchObject({ start: null, end: '2030-04-15' })
  await page.reload()
  await expect(page.getByText(t.name, { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'شهري', exact: true })).toHaveAttribute('aria-pressed', 'true')
  const shortMarker = page.locator(`[data-milestone-id="${markers[0].id}"]`)
  const longMarker = page.locator(`[data-milestone-id="${markers[1].id}"]`)
  await expect(shortMarker).toBeVisible()
  const center = async (locator: typeof shortMarker) => locator.evaluate(el => { const box = el.getBoundingClientRect(); return box.x + box.width / 2 })
  expect(Math.abs(await center(shortMarker) - await center(longMarker))).toBeLessThan(1)
  await page.screenshot({ path: test.info().outputPath('gantt-ar.png'), fullPage: true })
})

