test.skip(process.env.E2E_PHASE1_ISOLATED !== '1', 'Requires an explicitly isolated phase-one runtime')

async function json(response: APIResponse, status = 200) {
  expect(response.status(), await response.text()).toBe(status)
  return response.json()
}
async function project(page: Page, label: string) {
  return json(await page.request.post('/api/v1/projects', {
    data: { name: `${label} ${Date.now()}`, date_end: '2035-12-31', allow_task_dependencies: true },
  }), 201)
}
async function task(page: Page, projectId: number, name: string) {
  return json(await page.request.post('/api/v1/tasks', { data: { name, project_id: projectId } }), 201)
}

