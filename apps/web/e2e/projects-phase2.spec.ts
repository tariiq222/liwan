import { expect, test, type Page } from '@playwright/test'
import { FinanceEntrySchema, FinanceEntryListSchema, FinanceSummarySchema, ProjectReportListSchema } from '@nasq/contracts'

const LOGIN = process.env.E2E_PHASE2_LOGIN ?? 'phase2_manager'
const PASSWORD = process.env.E2E_PHASE2_PASSWORD ?? 'phase2_test_only_2026'

async function login(page: Page, loginName = LOGIN) {
  await page.goto('/login')
  const submit = page.getByRole('button', { name: 'دخول', exact: true })
  await expect(submit).toBeEnabled()
  await page.getByLabel('اسم المستخدم').fill(loginName)
  await page.getByLabel('كلمة المرور').fill(PASSWORD)
  await submit.click()
  await expect(page).not.toHaveURL(/\/login/)
}
async function createProject(page: Page, suffix: string) {
  const result = await page.request.post('/api/v1/projects', { data: { name: `Phase2 ${suffix} ${Date.now()}`, date_end: '2035-12-31' } })
  expect(result.status()).toBe(201)
  return result.json() as Promise<{ id: number; name: string }>
}

test('finance API preserves actual ledger, unknown budgets, revisions and complete report totals', async ({ page }) => {
  await login(page)
  const project = await createProject(page, 'ledger')
  const path = `/api/v1/projects/${project.id}/finance`
  const before = FinanceSummarySchema.parse(await (await page.request.get(`${path}/summary`)).json())
  expect(before).toMatchObject({ planned: null, actual: 0, remaining: null, budget_count: 0 })
  const budgetResult = await page.request.post(path, { data: { kind: 'budget', title: 'Infrastructure', amount: 1000 } })
  expect(budgetResult.status()).toBe(201)
  const budget = FinanceEntrySchema.parse(await budgetResult.json())
  const expenseResult = await page.request.post(path, { data: { kind: 'expense', title: 'Hosting invoice', amount: 250, expense_date: '2026-09-07', budget_entry_id: budget.id } })
  expect(expenseResult.status()).toBe(201)
  const expense = FinanceEntrySchema.parse(await expenseResult.json())
  const filtered = FinanceEntryListSchema.parse(await (await page.request.get(`${path}?kind=budget&q=nothing`)).json())
  expect(filtered.items).toEqual([])
  expect(filtered.total).toBe(0)
  expect(filtered.summary).toMatchObject({ planned: 1000, actual: 250, remaining: 750, utilization_percent: 25, budget_count: 1, expense_count: 1 })
  const refused = await page.request.delete(`${path}/${budget.id}`, { data: { expected_updated_at: budget.updated_at } })
  expect(refused.status()).toBe(409)
  const edit = await page.request.patch(`${path}/${expense.id}`, { data: { amount: 300, expected_updated_at: expense.updated_at } })
  expect(edit.status()).toBe(200)
  const updated = FinanceEntrySchema.parse(await edit.json())
  expect(updated.amount).toBe(300)
  expect(updated.updated_at).not.toBe(expense.updated_at)
  const stale = await page.request.patch(`${path}/${expense.id}`, { data: { amount: 500, expected_updated_at: expense.updated_at } })
  expect(stale.status()).toBe(409)
  const reports = ProjectReportListSchema.parse(await (await page.request.get(`/api/v1/reports/projects?q=${encodeURIComponent(project.name)}&limit=1`)).json())
  expect(reports.total).toBe(1)
  expect(reports.items[0]?.finance).toMatchObject({ actual: 300, remaining: 700 })
  expect(reports.totals[0]).toMatchObject({ project_count: 1, planned: 1000, actual: 300, remaining: 700 })
  expect((await page.request.delete(`${path}/${expense.id}`, { data: { expected_updated_at: updated.updated_at } })).status()).toBe(200)
  expect((await page.request.delete(`${path}/${budget.id}`, { data: { expected_updated_at: budget.updated_at } })).status()).toBe(200)
  const after = FinanceSummarySchema.parse(await (await page.request.get(`${path}/summary`)).json())
  expect(after).toMatchObject({ planned: null, actual: 0, remaining: null })
})

