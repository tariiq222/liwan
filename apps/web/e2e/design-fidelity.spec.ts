import { expect, test, type Page } from '@playwright/test'

async function login(page: Page) {
  await page.goto('/login')
  await page.getByLabel('اسم المستخدم').fill('admin')
  await page.getByLabel('كلمة المرور').fill('admin')
  await page.getByRole('button', { name: 'دخول', exact: true }).click()
  // Login lands on the first section the user may open (accessPolicy.firstAllowedPath).
  await expect(page).not.toHaveURL(/\/login(?:\?|$)/)
}

async function fixture(page: Page) {
  const name = `Fidelity ${Date.now()}`
  const response = await page.request.post('/api/v1/projects', { data: { name, date_end: '2035-12-31' } })
  expect(response.ok()).toBeTruthy()
  const project = await response.json()
  const taskResponse = await page.request.post('/api/v1/tasks', { data: { name: `${name} task`, project_id: project.id } })
  expect(taskResponse.ok()).toBeTruthy()
  return { project, task: await taskResponse.json() }
}

test('project views share the approved toolbar and keep filters when opening a card', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login(page)
  const { project } = await fixture(page)
  await page.goto(`/projects?view=table&q=${encodeURIComponent(project.name)}`)
  await expect(page.getByTestId('projects-toolbar')).toBeVisible()
  await expect(page.getByTestId('project-new')).toBeVisible()
  await expect(page.getByTestId('project-row')).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath('projects-desktop.png'), fullPage: true })
  await page.getByTestId('projects-view-cards').click()
  await expect(page.getByTestId('project-row')).toHaveCount(0)
  await page.getByRole('link', { name: project.name, exact: true }).click()
  await expect(page.locator('h1')).toHaveText(project.name)
  expect(new URL(page.url()).searchParams.get('returnTo')).toContain(`q=${encodeURIComponent(project.name).replace(/%20/g, '+')}`)
})

test('project task view sits inside its tab and hides the support rail', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login(page)
  const { project, task } = await fixture(page)
  await page.goto(`/projects/${project.id}`)
  await expect(page.locator('h1')).toHaveText(project.name)
  await expect(page.getByTestId('project-support-rail')).toBeVisible()
  await expect(page.getByTestId('project-overview')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('project-overview.png'), fullPage: true })
  await page.goto(`/projects/${project.id}?tab=tasks&view=table`)
  await expect(page.getByTestId('project-support-rail')).not.toBeVisible()
  const taskRow = page.getByRole('row').filter({ hasText: task.name })
  await expect(taskRow).toBeVisible()
  await taskRow.getByRole('button', { name: task.name, exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.locator('h1')).toHaveText(task.name)
  await expect(page).toHaveURL(new RegExp(`/projects/${project.id}/tasks/${task.id}`))
})

test('task details use tabs and title editing remains explicit', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login(page)
  const { project, task } = await fixture(page)
  await page.goto(`/projects/${project.id}/tasks/${task.id}`)
  await expect(page.locator('h1')).toHaveText(task.name)
  await expect(page.getByTestId('task-title-input')).toHaveValue(task.name)
  const tabs = page.getByTestId('task-detail-tabs')
  await expect(tabs).toBeVisible()
  await expect(tabs.getByRole('tab', { name: 'التفاصيل', exact: true })).toHaveAttribute('data-state', 'active')
  await expect(page.getByTestId('task-activity-card')).toBeHidden()
  await tabs.getByRole('tab', { name: 'السجل', exact: true }).click()
  await expect(page.getByTestId('task-activity-card')).toBeVisible()
  const titleInput = page.getByTestId('task-title-input')
  await titleInput.fill(`${task.name} edited`)
  await titleInput.press('Enter')
  await expect(page.locator('h1')).toHaveText(`${task.name} edited`)
  await page.reload()
  await expect(page.locator('h1')).toHaveText(`${task.name} edited`)
  await page.screenshot({ path: testInfo.outputPath('task-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await expect(page.getByTestId('task-detail-tabs').getByRole('tab', { name: 'التفاصيل', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('task-mobile.png'), fullPage: true })
})

test('settings use side navigation on desktop and stack on mobile', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login(page)
  await page.request.patch('/api/v1/me/appearance', { data: { mode: 'dark', font_size: 'large' } })
  await page.goto('/settings/company/branding')
  const nav = page.locator('.webvue-settings-nav')
  const form = page.getByTestId('branding-form')
  await expect(form).toBeVisible()
  const [navBox, formBox] = await Promise.all([nav.boundingBox(), form.boundingBox()])
  expect(navBox!.width).toBe(220)
  expect(Math.abs(navBox!.y - formBox!.y)).toBeLessThan(2)
  await expect(page.locator('html')).toHaveClass(/dark/)
  await expect(page.getByRole('button', { name: 'بحث', exact: true })).toHaveCSS('background-color', 'rgb(39, 39, 42)')
  await page.screenshot({ path: testInfo.outputPath('settings-desktop-dark.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  const [smallNav, smallForm] = await Promise.all([nav.boundingBox(), form.boundingBox()])
  expect(smallForm!.y).toBeGreaterThan(smallNav!.y + smallNav!.height)
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
  await page.screenshot({ path: testInfo.outputPath('settings-mobile-dark.png'), fullPage: true })
})


test('HR directory, employee details and forms retain a responsive page hierarchy', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await login(page)
  const response = await page.request.get('/api/v1/hr/employees?limit=1')
  expect(response.ok()).toBeTruthy()
  const { items } = await response.json()
  expect(items.length).toBeGreaterThan(0)
  for (const [name, url] of [['hr-directory', '/hr'], ['employee', `/hr/employees/${items[0].id}`], ['employee-edit', `/hr/employees/${items[0].id}/edit`]] as const) {
    await page.goto(url)
    await expect(page.locator('h1')).toHaveCount(1)
    if (name === 'hr-directory') await expect(page.getByRole('table')).toBeVisible()
    else await expect(page.locator('h1')).toHaveText(name === 'employee' ? items[0].name : 'تعديل الموظف')
    await page.screenshot({ path: testInfo.outputPath(`${name}.png`), fullPage: true })
    await page.setViewportSize({ width: 390, height: 844 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1)
    await page.screenshot({ path: testInfo.outputPath(`${name}-mobile.png`), fullPage: true })
    await page.setViewportSize({ width: 1440, height: 1000 })
  }
})
