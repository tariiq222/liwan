it('registers immutable branch quotes and revision guard in versions fifteen and sixteen once', async () => {
  const applied = Array.from({length:14}, (_, i) => i+1)
  const f=fixture(applied)
  await migrate(f.pool)
  const sql=f.query.mock.calls.map(([s])=>s)
  expect(sql).toContain('INSERT INTO schema_migrations(version) VALUES(15)')
  expect(sql).toContain('INSERT INTO schema_migrations(version) VALUES(16)')
  expect(sql.some(s=>s.includes('CREATE TABLE branch_quote_requests'))).toBe(true)
  expect(sql.indexOf('INSERT INTO schema_migrations(version) VALUES(16)')).toBeGreaterThan(sql.indexOf('INSERT INTO schema_migrations(version) VALUES(15)'))
  expect(sql).toContain('INSERT INTO schema_migrations(version) VALUES(17)')
  expect(sql).toContain('INSERT INTO schema_migrations(version) VALUES(18)')
  expect(sql.some(s=>s.includes('ADD COLUMN enrollment_request_id uuid UNIQUE'))).toBe(true)
  const g=fixture([...applied,15,16,17,18]); await migrate(g.pool)
  expect(g.query.mock.calls.map(([s])=>s)).not.toContain('INSERT INTO schema_migrations(version) VALUES(17)')
  expect(g.query.mock.calls.map(([s])=>s)).not.toContain('INSERT INTO schema_migrations(version) VALUES(18)')
  expect(g.query.mock.calls.map(([s])=>s)).not.toContain('INSERT INTO schema_migrations(version) VALUES(15)')
  expect(g.query.mock.calls.map(([s])=>s)).not.toContain('INSERT INTO schema_migrations(version) VALUES(16)')
})
