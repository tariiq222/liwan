#!/bin/sh
# Renders the ai-egress Squid configuration from AI_EGRESS_HOSTS and writes it once, atomically.
#   sh render.sh [config path]        (default: $SQUID_CONF, then /run/squid/squid.conf)
# AI_EGRESS_HOSTS is a comma-separated list; each item is
#   host        allow CONNECT to port 443 only,
#   host:port   allow exactly that port, CONNECT and plain HTTP (a local model server such as ollama:11434).
# An empty list is valid and denies everything. A malformed item fails before anything is written, so a bad
# value never replaces a working configuration.
#
# AI_TENANT_EGRESS_DIR (optional) is the directory the ai service writes the provider hosts of tenants' own keys into,
# one <tenant database>.hosts file per tenant with one hostname per line. Those hosts are reachable by CONNECT to port
# 443 only, and only while the destination is not a private, loopback, link-local, CGNAT, multicast or reserved address
# (checked by squid when it connects, so a name that resolves privately later is refused too). The files are written
# by another container, so a bad line is logged and skipped here, never a reason to fail: it must not take the proxy down.
set -eu

conf="${1:-${SQUID_CONF:-/run/squid/squid.conf}}"
hosts="${AI_EGRESS_HOSTS:-}"
tenant_dir="${AI_TENANT_EGRESS_DIR:-}"

fail() {
  echo "ai-egress: $1" >&2
  exit 1
}

is_host() {
  printf '%s' "$1" | grep -Eqx '[a-z0-9]([a-z0-9.-]{0,251}[a-z0-9])?'
}

is_port() {
  case "$1" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "${#1}" -le 5 ] && [ "$1" -ge 1 ] && [ "$1" -le 65535 ]
}

# The valid hosts of the tenant files, one per line, sorted and unique. Invalid or unreadable input is logged and skipped.
tenant_hosts() {
  [ -n "$tenant_dir" ] || return 0
  for file in "$tenant_dir"/*.hosts; do
    [ -f "$file" ] || continue
    if [ ! -r "$file" ]; then
      echo "ai-egress: skipping unreadable tenant host file $(basename "$file")" >&2
      continue
    fi
    while IFS= read -r line || [ -n "$line" ]; do
      line="$(printf '%s' "$line" | tr -d '[:space:]')"
      case "$line" in
        ''|'#'*) continue ;;
      esac
      if is_host "$line"; then
        printf '%s\n' "$line"
      else
        echo "ai-egress: skipping invalid tenant host in $(basename "$file"): $(printf '%s' "$line" | cut -c1-64)" >&2
      fi
    done < "$file"
  done | sort -u
}

# A value of spaces only (a stray indent in deploy/.env) is the same as an empty list: deny everything.
case "$hosts" in
  *[![:space:]]*) ;;
  *) hosts='' ;;
esac

# Validate the whole list first: the file is only written once every item is known to be sound.
if [ -n "$hosts" ]; then
  case "$hosts" in
    *,|,*) fail "AI_EGRESS_HOSTS has an empty item: '$hosts'" ;;
  esac
fi
entries=''
rest="$hosts"
while [ -n "$rest" ]; do
  case "$rest" in
    *,*) item="${rest%%,*}"; rest="${rest#*,}" ;;
    *) item="$rest"; rest='' ;;
  esac
  [ -n "$item" ] || fail "AI_EGRESS_HOSTS has an empty item: '$hosts'"
  case "$item" in
    *:*) host="${item%:*}"; port="${item##*:}" ;;
    *) host="$item"; port='' ;;
  esac
  is_host "$host" || fail "AI_EGRESS_HOSTS item '$item' is not a lowercase hostname"
  if [ -n "$port" ]; then
    is_port "$port" || fail "AI_EGRESS_HOSTS item '$item' has an invalid port"
  fi
  entries="$entries$item
"
done

tenant_list="$(tenant_hosts)"

mkdir -p "$(dirname "$conf")"
tmp="$conf.tmp.$$"
trap 'rm -f "$tmp"' EXIT INT TERM

{
  printf '%s\n' \
    '# Generated by deploy/ai-egress/render.sh from AI_EGRESS_HOSTS; rewritten at every container start and whenever the tenant hosts change.' \
    '' \
    'http_port 3128' \
    'visible_hostname ai-egress' \
    'pid_filename /run/squid/squid.pid' \
    'coredump_dir /run/squid' \
    'netdb_filename /run/squid/netdb.state' \
    'pinger_enable off' \
    '' \
    '# No caching: the gateway forwards and forgets.' \
    'cache deny all' \
    'cache_mem 8 MB' \
    'cache_store_log none' \
    'cache_log stdio:/dev/stderr' \
    'strip_query_terms on' \
    '' \
    '# One line per request: time, client, method, destination and status; never a header or a body.' \
    '# A CONNECT request — the only method any outside host is reachable with — carries exactly "host:port" in %ru,' \
    '# so an external request logs no path. Query strings are stripped for the plain-HTTP requests a listed' \
    '# internal host:port item allows (a local model server).' \
    'logformat liwan_egress %ts.%03tu %>a %rm %ru %Ss/%>Hs' \
    'access_log stdio:/dev/stdout liwan_egress' \
    '' \
    'acl egress_connect method CONNECT'

  if [ -n "$entries" ]; then
    index=0
    while IFS= read -r item; do
      [ -n "$item" ] || continue
      case "$item" in
        *:*) host="${item%:*}"; port="${item##*:}"; connect_only=no ;;
        *) host="$item"; port=443; connect_only=yes ;;
      esac
      index=$((index + 1))
      printf '\n# %s:%s\n' "$host" "$port"
      printf 'acl egress_host_%s dstdomain %s\n' "$index" "$host"
      printf 'acl egress_port_%s port %s\n' "$index" "$port"
      if [ "$connect_only" = yes ]; then
        printf 'http_access allow egress_host_%s egress_port_%s egress_connect\n' "$index" "$index"
      else
        printf 'http_access allow egress_host_%s egress_port_%s\n' "$index" "$index"
      fi
    done <<EOF
$entries
EOF
  fi

  if [ -n "$tenant_list" ]; then
    printf '\n# Tenant provider hosts: CONNECT to port 443 only, and never to a private destination.\n'
    # One ACL line per host: lines of the same name are alternatives, and no line grows with the number of tenants.
    for host in $tenant_list; do
      printf 'acl tenant_host dstdomain %s\n' "$host"
    done
    # An IPv4-mapped IPv6 address is matched by the IPv4 ranges: squid reads ::ffff:0:0/96 as 0.0.0.0/0, so it is not listed.
    printf '%s\n' \
      'acl tenant_port port 443' \
      'acl tenant_private dst 0.0.0.0/8 10.0.0.0/8 100.64.0.0/10 127.0.0.0/8 169.254.0.0/16 172.16.0.0/12 192.0.0.0/24 192.168.0.0/16 198.18.0.0/15 192.0.2.0/24 198.51.100.0/24 203.0.113.0/24 224.0.0.0/4 240.0.0.0/4 ::/128 ::1/128 64:ff9b::/96 64:ff9b:1::/48 100::/64 2001:db8::/32 2002::/16 fc00::/7 fe80::/10 ff00::/8' \
      'http_access deny tenant_host tenant_private' \
      'http_access allow tenant_host tenant_port egress_connect'
  fi

  printf '\n# Everything not allowed above is refused, and the refusal is logged by host.\n'
  printf 'http_access deny all\n'
} > "$tmp"

mv "$tmp" "$conf"
trap - EXIT INT TERM
