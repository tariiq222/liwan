#!/bin/sh
# Renders the ai-egress Squid configuration from AI_EGRESS_HOSTS and writes it once, atomically.
#   sh render.sh [config path]        (default: $SQUID_CONF, then /run/squid/squid.conf)
# AI_EGRESS_HOSTS is a comma-separated list; each item is
#   host        allow CONNECT to port 443 only,
#   host:port   allow exactly that port, CONNECT and plain HTTP (a local model server such as ollama:11434).
# An empty list is valid and denies everything. A malformed item fails before anything is written, so a bad
# value never replaces a working configuration.
set -eu

conf="${1:-${SQUID_CONF:-/run/squid/squid.conf}}"
hosts="${AI_EGRESS_HOSTS:-}"

fail() {
  echo "ai-egress: $1" >&2
  exit 1
}

is_host() {
  printf '%s' "$1" | grep -Eqx '[a-z0-9]([a-z0-9.-]{0,251}[a-z0-9])?'
}

is_port() {
  case "$1" in
    ''|*[!0-9]*) return 1 ;;
  esac
  [ "${#1}" -le 5 ] && [ "$1" -ge 1 ] && [ "$1" -le 65535 ]
}

# A value of spaces only (a stray indent in deploy/.env) is the same as an empty list: deny everything.
case "$hosts" in
  *[![:space:]]*) ;;
  *) hosts='' ;;
esac

# Validate the whole list first: the file is only written once every item is known to be sound.
if [ -n "$hosts" ]; then
  case "$hosts" in
    *,|,*) fail "AI_EGRESS_HOSTS has an empty item: '$hosts'" ;;
  esac
fi
entries=''
rest="$hosts"
while [ -n "$rest" ]; do
  case "$rest" in
    *,*) item="${rest%%,*}"; rest="${rest#*,}" ;;
    *) item="$rest"; rest='' ;;
  esac
  [ -n "$item" ] || fail "AI_EGRESS_HOSTS has an empty item: '$hosts'"
  case "$item" in
    *:*) host="${item%:*}"; port="${item##*:}" ;;
    *) host="$item"; port='' ;;
  esac
  is_host "$host" || fail "AI_EGRESS_HOSTS item '$item' is not a lowercase hostname"
  if [ -n "$port" ]; then
    is_port "$port" || fail "AI_EGRESS_HOSTS item '$item' has an invalid port"
  fi
  entries="$entries$item
"
done

mkdir -p "$(dirname "$conf")"
tmp="$conf.tmp.$$"
trap 'rm -f "$tmp"' EXIT INT TERM

{
  printf '%s\n' \
    '# Generated by deploy/ai-egress/render.sh from AI_EGRESS_HOSTS; rewritten at every container start.' \
    '' \
    'http_port 3128' \
    'visible_hostname ai-egress' \
    'pid_filename /run/squid/squid.pid' \
    'coredump_dir /run/squid' \
    'netdb_filename /run/squid/netdb.state' \
    'pinger_enable off' \
    '' \
    '# No caching: the gateway forwards and forgets.' \
    'cache deny all' \
    'cache_mem 8 MB' \
    'cache_store_log none' \
    'cache_log stdio:/dev/stderr' \
    'strip_query_terms on' \
    '' \
    '# One line per request: time, client, method, destination and status; never a header or a body.' \
    '# A CONNECT request — the only method any outside host is reachable with — carries exactly "host:port" in %ru,' \
    '# so an external request logs no path. Query strings are stripped for the plain-HTTP requests a listed' \
    '# internal host:port item allows (a local model server).' \
    'logformat liwan_egress %ts.%03tu %>a %rm %ru %Ss/%>Hs' \
    'access_log stdio:/dev/stdout liwan_egress' \
    '' \
    'acl egress_connect method CONNECT'

  if [ -n "$entries" ]; then
    index=0
    while IFS= read -r item; do
      [ -n "$item" ] || continue
      case "$item" in
        *:*) host="${item%:*}"; port="${item##*:}"; connect_only=no ;;
        *) host="$item"; port=443; connect_only=yes ;;
      esac
      index=$((index + 1))
      printf '\n# %s:%s\n' "$host" "$port"
      printf 'acl egress_host_%s dstdomain %s\n' "$index" "$host"
      printf 'acl egress_port_%s port %s\n' "$index" "$port"
      if [ "$connect_only" = yes ]; then
        printf 'http_access allow egress_host_%s egress_port_%s egress_connect\n' "$index" "$index"
      else
        printf 'http_access allow egress_host_%s egress_port_%s\n' "$index" "$index"
      fi
    done <<EOF
$entries
EOF
  fi

  printf '\n# Everything not allowed above is refused, and the refusal is logged by host.\n'
  printf 'http_access deny all\n'
} > "$tmp"

mv "$tmp" "$conf"
trap - EXIT INT TERM
