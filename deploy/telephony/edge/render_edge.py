"""Render the shared telephony edge route from the control plane's snapshot.

A company host is the tenant host liwan already serves (`<company>.<deployment domain>`), so the two telephony paths
are not a site of their own: ``deploy/stack/Caddyfile`` imports this snippet *inside* the tenant site and before the
guard, and the snippet forwards exactly two paths of the hosts the snapshot names (design 11.2, 12.3):

- ``/ws`` to that company's Asterisk, carrying the real client address so Asterisk keys failed SIP registrations by
  impersonation and address (11.3). Caddy forwards the WebSocket upgrade itself.
- ``GET /pbx/recordings/<token>`` to that company's ``pbx-agent``; any other method on that path is not forwarded.

Nothing else is forwarded here, ``/ari`` among it. The 404 lives in ``deploy/stack/Caddyfile`` for every tenant host,
so a company host that is absent from the snapshot and a snapshot file that is missing answer the same 404.

The snapshot is ``telephony-registry.json``, published atomically by the control plane:

    {"companies": {"<host>": {"asterisk": "host:port", "agent": "host:port"}}}

It is read with the barrier of ``apps/web/server/utils/tenantRegistry.ts``: a ``.pending`` marker beside it marks an
interrupted publication and is refused, and the file's identity is compared before and after the read, so a
replacement under the read is never bound. An invalid snapshot is refused before anything is written, so a refused
run leaves the last good snippet in place instead of half-replacing it. The output is deterministic (hosts in sorted
order, no timestamp and no counter), so the same snapshot always renders the same bytes.

Nothing here prints a value: a refusal names the company host and the field, and the summary prints the file name and
a count.

    python3 -B deploy/telephony/edge/render_edge.py --snapshot <telephony-registry.json> --out <telephony.caddy>
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path

SNAPSHOT_NAME = 'telephony-registry.json'
PENDING_SUFFIX = '.pending'
TOP_LEVEL_KEYS = frozenset({'companies'})
COMPANY_FIELDS = ('agent', 'asterisk')
# The same host rule the control plane's telephony effect accepts for a company host
# (tools/shared_saas_lifecycle/tenant_telephony_effect.py), so a host that cannot be recorded cannot be routed.
HOST = re.compile(r'(?=.{1,253}$)[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?(?:\.[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?)+')
# The token form of design 4.4: the agent's own route takes one path segment, so the edge takes exactly that one.
RECORDING_TOKEN = '[A-Za-z0-9_.-]+'
MAX_PORT = 65535
FILE_MODE = 0o644
EXIT_USAGE = 2
USAGE = 'usage: render_edge.py --snapshot <telephony-registry.json> --out <telephony.caddy>\n'

HEADER = (
    '# Generated by deploy/telephony/edge/render_edge.py from %s; do not edit.' % SNAPSHOT_NAME,
    '# Imported by deploy/stack/Caddyfile inside the tenant site, above the guard, so both paths are decided before any',
    '# liwan route sees them. Only /ws and GET /pbx/recordings/<token> are forwarded; the Caddyfile answers every other',
    '# path of a company host, /ari among them, with 404.',
)


class SnapshotError(Exception):
    """The snapshot cannot produce a route: absent, unreadable, half published or shaped otherwise than the contract."""


def _identity(path: Path) -> tuple[int, int, int, int, int]:
    """The filesystem identity a read is bound to, as in ``tenantRegistry.ts``: the file, not a TTL, decides."""
    try:
        info = os.stat(path)
    except OSError:
        raise SnapshotError(f'{SNAPSHOT_NAME} cannot be read') from None
    return info.st_dev, info.st_ino, info.st_size, info.st_mtime_ns, info.st_ctime_ns


def require_completed_publication(path: Path) -> None:
    """A writer creates ``<name>.pending`` before committing authority changes; an interrupted publication is refused.

    The edge must not route a host from the old snapshot while a new one is half in place, so a marker seen before or
    after the read denies it, exactly as an unreadable snapshot does.
    """
    marker = path.with_name(path.name + PENDING_SUFFIX)
    try:
        marker.lstat()
    except FileNotFoundError:
        return
    except OSError:
        raise SnapshotError(f'{SNAPSHOT_NAME} publication cannot be checked') from None
    raise SnapshotError(f'{SNAPSHOT_NAME} is being published (a {PENDING_SUFFIX} marker is present)')


def _object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    """A JSON object, refusing a repeated key: ``json`` would keep the last silently, dropping a company's route."""
    result: dict[str, object] = {}
    for key, value in pairs:
        if key in result:
            raise SnapshotError(f'{SNAPSHOT_NAME} repeats a key in one object')
        result[key] = value
    return result


def parse(body: bytes) -> object:
    try:
        return json.loads(body.decode('utf-8'), object_pairs_hook=_object)
    except UnicodeDecodeError:
        raise SnapshotError(f'{SNAPSHOT_NAME} is not UTF-8') from None
    except ValueError:
        raise SnapshotError(f'{SNAPSHOT_NAME} is not valid JSON') from None


def _port(text: str) -> bool:
    """ASCII digits only, so a look-alike digit cannot pass for a port."""
    return text.isascii() and text.isdigit() and 1 <= int(text) <= MAX_PORT


def upstream(value: object, host: str, field: str) -> str:
    """One ``host:port`` upstream, validated before it can reach the generated file."""
    if isinstance(value, str):
        name, separator, port = value.rpartition(':')
        if separator and _port(port) and HOST.fullmatch(name):
            return value
    raise SnapshotError(f'companies[{host}].{field} must be "host:port", a lowercase host name or IPv4 address '
                        f'and a port between 1 and {MAX_PORT}')


def validate(value: object) -> dict[str, dict[str, str]]:
    """The snapshot as ``{host: {"asterisk": ..., "agent": ...}}``, or a refusal that names the host and the field."""
    if not isinstance(value, dict) or set(value) != TOP_LEVEL_KEYS:
        raise SnapshotError(f'{SNAPSHOT_NAME} must hold exactly {{"companies": {{...}}}}')
    companies = value['companies']
    if not isinstance(companies, dict):
        raise SnapshotError(f'{SNAPSHOT_NAME} "companies" must be an object keyed by company host')
    checked: dict[str, dict[str, str]] = {}
    for host, target in companies.items():
        if not HOST.fullmatch(host):
            raise SnapshotError(f'company host {host!r} is not a lowercase host name')
        if not isinstance(target, dict) or set(target) != set(COMPANY_FIELDS):
            raise SnapshotError(f'companies[{host}] must hold exactly {", ".join(COMPANY_FIELDS)}')
        checked[host] = {field: upstream(target[field], host, field) for field in COMPANY_FIELDS}
    return checked


def read_snapshot(path: Path) -> dict[str, dict[str, str]]:
    """The validated snapshot, or a refusal. A marker before or after the read, or a replaced file, is refused."""
    require_completed_publication(path)
    identity = _identity(path)
    try:
        body = path.read_bytes()
    except OSError:
        raise SnapshotError(f'{SNAPSHOT_NAME} cannot be read') from None
    companies = validate(parse(body))
    # A writer may complete after the first check, and a replacement under the read binds nothing.
    if _identity(path) != identity:
        raise SnapshotError(f'{SNAPSHOT_NAME} changed while it was read')
    require_completed_publication(path)
    return companies


def _websocket(index: int, host: str, asterisk: str) -> list[str]:
    """The browser leg: ``wss://<company host>/ws`` to that company's Asterisk (design 12.8 decision 2)."""
    return [
        f'@telephony_websocket_{index} {{',
        f'\thost {host}',
        '\tpath /ws',
        '}',
        f'reverse_proxy @telephony_websocket_{index} {asterisk} {{',
        # Asterisk keys failed SIP registrations by impersonation and address together (11.3), so it needs the real
        # client; `client_ip` is the peer, or the address an outer edge appended, never a header the browser wrote.
        '\theader_up X-Forwarded-For {client_ip}',
        # The edge's own private headers never cross to a PBX host (the guard's rule in deploy/stack/Caddyfile).
        '\theader_up -X-Liwan-Proxy-Token',
        '\theader_up -X-Liwan-Tenant-Revision',
        '\theader_up -X-Liwan-Client-Ip',
        '\theader_up -X-Liwan-Signup-Client',
        '\theader_up -Forwarded',
        '}',
    ]


def _recording(index: int, host: str, agent: str) -> list[str]:
    """The signed recording link of design 4.4: one GET path segment, nothing else, to that company's agent."""
    return [
        f'@telephony_recording_{index} {{',
        f'\thost {host}',
        '\tmethod GET',
        f'\tpath_regexp telephony_recording_token_{index} ^/pbx/recordings/{RECORDING_TOKEN}$',
        '}',
        f'reverse_proxy @telephony_recording_{index} {agent} {{',
        '\theader_up -X-Liwan-Proxy-Token',
        '\theader_up -X-Liwan-Tenant-Revision',
        '\theader_up -X-Liwan-Client-Ip',
        '\theader_up -X-Liwan-Signup-Client',
        '\theader_up -Forwarded',
        '}',
    ]


def snippet(companies: dict[str, dict[str, str]]) -> str:
    """The Caddy snippet: one ordered ``route`` group, one host at a time in sorted order, so the bytes are stable."""
    lines = list(HEADER)
    lines.append('route {')
    for index, host in enumerate(sorted(companies)):
        target = companies[host]
        lines.append(f'\t# {host}')
        lines.extend('\t' + line for line in _websocket(index, host, target['asterisk']))
        lines.extend('\t' + line for line in _recording(index, host, target['agent']))
    lines.append('}')
    return '\n'.join(lines) + '\n'


def render(path: Path) -> str:
    """The snippet for one snapshot file. Reading and validating happen before any byte is written."""
    return snippet(read_snapshot(path))


def write_snippet(out: Path, text: str) -> None:
    """Replace ``out`` in one rename, so a running Caddy rereads a whole file and never a half-written one."""
    temporary = out.with_name(out.name + '.tmp')
    descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, FILE_MODE)
    try:
        with os.fdopen(descriptor, 'w', encoding='utf-8') as handle:
            handle.write(text)
        os.replace(temporary, out)
    except OSError:
        try:
            os.unlink(temporary)
        except OSError:
            pass
        raise
    out.chmod(FILE_MODE)


def main(argv: list[str]) -> int:
    snapshot = out = None
    arguments = iter(argv)
    for argument in arguments:
        value = next(arguments, None)
        if value is None or argument not in ('--snapshot', '--out'):
            sys.stderr.write(USAGE)
            return EXIT_USAGE
        if argument == '--snapshot':
            snapshot = Path(value)
        else:
            out = Path(value)
    if snapshot is None or out is None:
        sys.stderr.write(USAGE)
        return EXIT_USAGE
    try:
        text = render(snapshot)
    except SnapshotError as error:
        sys.stderr.write(f'render_edge: {error}\n')
        return 1
    except OSError as error:
        sys.stderr.write(f'render_edge: {error.filename or snapshot}: {error.strerror}\n')
        return 1
    try:
        write_snippet(out, text)
    except OSError as error:
        sys.stderr.write(f'render_edge: {error.filename or out}: {error.strerror}\n')
        return 1
    sys.stdout.write(f'render_edge: wrote {out}\n')
    sys.stdout.write(f'render_edge: {len(text.splitlines())} lines\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main(sys.argv[1:]))
