"""The extension: a desk phone or a browser seat, bound to one employee and one company.

It holds no password. The session password is generated by ``pbx-agent`` for each registration and never stored here
(design 4.1), so a leaked Odoo backup cannot be used to place calls.
"""
from odoo import fields, models


class LiwanTelephonyExtension(models.Model):
    _name = 'liwan.telephony.extension'
    _description = 'Telephony extension'
    _liwan_scope = 'company'
    _order = 'number'
    _rec_name = 'number'

    number = fields.Char(required=True, index=True)
    user_id = fields.Many2one('res.users', index=True)
    active = fields.Boolean(default=True)
    company_id = fields.Many2one(
        'res.company', required=True, default=lambda self: self.env.company, index=True,
    )

    _sql_constraints = [
        ('number_company_unique', 'unique(number, company_id)', 'An extension number is unique in a company.'),
    ]
