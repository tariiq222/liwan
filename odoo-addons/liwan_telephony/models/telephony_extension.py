"""The extension: a desk phone or a browser seat, bound to one employee and one company.

It holds no password. The session password is generated by ``pbx-agent`` for each registration and never stored here
(design 4.1), so a leaked Odoo backup cannot be used to place calls.
"""
from odoo import api, fields, models

from .res_company import lookup_order

EXTENSION_NUMBER = r'^[0-9]{2,10}$'


class LiwanTelephonyExtension(models.Model):
    _name = 'liwan.telephony.extension'
    _description = 'Telephony extension'
    _liwan_scope = 'company'
    _order = 'number'
    _rec_name = 'number'

    number = fields.Char(required=True, index=True)
    user_id = fields.Many2one('res.users', index=True)
    active = fields.Boolean(default=True)
    company_id = fields.Many2one(
        'res.company', required=True, default=lambda self: self.env.company, index=True,
    )

    _number_unique = models.Constraint('unique(number)', 'An extension number is unique across the tenant.')
    _number_digits = models.Constraint(
        f"CHECK(number ~ '{EXTENSION_NUMBER}')", 'An extension number is 2 to 10 digits.',
    )

    @api.model
    def _liwan_by_number(self, number, company=None):
        """The extension with ``number`` in the tenant, or none: of ``company`` when it has one, else of any other
        company the caller belongs to.

        Extension numbers are unique across the tenant database (one Asterisk/pbx-agent namespace). The caller's
        record rules and company scope decide which companies are searched.
        """
        for company_id in lookup_order(self.env.user, company):
            found = self.with_company(company_id).search([('number', '=', number)], limit=1)
            if found:
                return found
        return self.browse()
